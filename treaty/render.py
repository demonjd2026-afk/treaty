"""Output: a short Markdown report sized for a chat message, JSON, and a
compatibility view for renames."""

from __future__ import annotations

import datetime as dt
import json

from .diff import BREAKING, SAFE, WARNING, DiffResult
from .lineage import Impact

ICON = {BREAKING: "🔴", WARNING: "🟡", SAFE: "🟢"}
LABEL = {BREAKING: "BREAKING", WARNING: "NEEDS REVIEW", SAFE: "SAFE"}


def markdown(result: DiffResult, impacts: list[Impact], contract_path: str = "") -> str:
    b, h = result.base, result.head
    lines = [f"**Treaty check · `{h.name}` {b.version_str} → {h.version_str}** · "
             f"{ICON[result.verdict]} **{LABEL[result.verdict]}**", ""]

    if not result.changes:
        lines.append("No schema or SLA changes.")
    else:
        lines.append("**Changes**")
        lines += [f"- {ICON[c.severity]} {c.message}" for c in result.changes]

    lines.append("")
    if result.version_ok:
        lines.append(f"**Version** ✅ {result.declared_bump} bump declared (required: {result.required_bump})")
    else:
        lines.append(f"**Version** ❌ declared `{h.version_str}` is a {result.declared_bump} bump; "
                     f"this change needs a **{result.required_bump}** bump")

    if impacts:
        n_hit = sum(1 for i in impacts if i.status != SAFE)
        lines += ["", f"**Consumer impact** ({n_hit} of {len(impacts)} affected)"]
        for i in impacts:
            c = i.consumer
            row = f"- {ICON[i.status]} **{c.asset}** · {c.team} · owner: {c.owner}"
            if i.columns:
                row += " · uses " + ", ".join(f"`{x}`" for x in i.columns)
            if i.literal_hits:
                row += " · SQL filters on " + ", ".join(repr(x) for x in i.literal_hits)
            lines.append(row)
        drift = [i for i in impacts if i.undeclared]
        if drift:
            lines += ["", "**Lineage drift** (used in SQL, not declared in consumers.yaml)"]
            lines += [f"- `{i.consumer.id}` reads " + ", ".join(f"`{x}`" for x in i.undeclared) for i in drift]

    lines.append("")
    if result.verdict == BREAKING:
        owners = sorted({i.consumer.owner for i in impacts if i.status == BREAKING})
        who = ", ".join(owners) if owners else "the consumer owners"
        lines.append(f"**Next** sign-off required from: {who}. Do not merge until every one approves.")
        if result.renames and contract_path:
            lines.append(f"Compatibility shim available: `treaty shim {contract_path} --base <ref>`")
    elif result.verdict == WARNING:
        lines.append("**Next** non-breaking, but tell affected owners before merging.")
    else:
        lines.append("**Next** safe to merge.")
    return "\n".join(lines)


def as_json(result: DiffResult, impacts: list[Impact]) -> str:
    return json.dumps({
        "contract": result.head.name,
        "base_version": result.base.version_str,
        "head_version": result.head.version_str,
        "verdict": result.verdict,
        "required_bump": result.required_bump,
        "declared_bump": result.declared_bump,
        "version_ok": result.version_ok,
        "renames": result.renames,
        "changes": [{"kind": c.kind, "severity": c.severity, "column": c.column, "message": c.message}
                    for c in result.changes],
        "impact": [{"consumer": i.consumer.id, "asset": i.consumer.asset, "owner": i.consumer.owner,
                    "room": i.consumer.room, "status": i.status, "columns": i.columns,
                    "undeclared": i.undeclared, "literal_hits": i.literal_hits} for i in impacts],
    }, indent=2, ensure_ascii=False)


def shim_sql(result: DiffResult, until: dt.date) -> str:
    """A view that keeps the old column names readable during a deprecation window."""
    b, h = result.base, result.head
    view = f"{b.dataset}_v{b.version[0]}_compat"
    out = [f"-- Compatibility view: {b.name} {b.version_str} column names on top of {h.version_str}.",
           f"-- Deprecated; drop after {until.isoformat()}. Generated by `treaty shim`.",
           f"create or replace view {view} as", "select"]
    exprs, notes = [], []
    for c in result.changes:
        if c.kind == "meaning_changed":
            notes.append(f"-- WARNING: {c.message.replace('`', '')}")
    for name, old in b.columns.items():
        if name in h.columns:
            new = h.columns[name]
            expr = name if new.type == old.type else f"cast({name} as {old.type})"
            exprs.append(f"    {expr} as {name}" if expr != name else f"    {name}")
        elif name in result.renames:
            new_name = result.renames[name]
            new = h.columns[new_name]
            src = new_name if new.type == old.type else f"cast({new_name} as {old.type})"
            exprs.append(f"    {src} as {name}")
        else:
            exprs.append(f"    cast(null as {old.type}) as {name}")
            notes.append(f"-- WARNING: `{name}` was removed with no replacement; the shim returns null.")
        if name in h.columns and old.enum and h.columns[name].enum:
            gone = [v for v in old.enum if v not in h.columns[name].enum]
            if gone:
                notes.append(f"-- WARNING: `{name}` no longer produces {gone}; a view cannot restore them.")
    out.append(",\n".join(exprs))
    out.append(f"from {h.dataset};")
    return "\n".join(notes + out) + "\n"
